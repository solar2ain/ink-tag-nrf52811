#!/usr/bin/env python3
"""Generate independent firmware version constants from version.json."""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path


def write_if_changed(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return
    path.write_text(content, encoding="utf-8", newline="\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[2])
    args = parser.parse_args()
    repo = args.repo.resolve()
    data = json.loads((repo / "version.json").read_text(encoding="utf-8"))

    major = int(data["major"])
    minor = int(data["minor"])
    patch = int(data["patch"])
    protocol = int(data["protocolVersion"])
    ota = int(data["otaVersion"])
    version = str(data["version"])
    recovery_version = str(data["recoveryVersion"])
    recovery_match = re.fullmatch(r"([1-9]\d*)\.(\d+)\.(\d+)", recovery_version)
    if recovery_match is None or any(int(v) > 255 for v in recovery_match.groups()):
        raise SystemExit("recoveryVersion must have byte fields and nonzero epoch")
    recovery_major, recovery_minor, recovery_patch = map(int, recovery_match.groups())
    expected_version = f"{major}.{minor}.{patch}"
    expected_ota = major * 10000 + minor * 100 + patch
    if version != expected_version:
        raise SystemExit(f"version must be {expected_version}, got {version}")
    if not all(0 <= value <= 255 for value in (major, minor, patch, protocol)):
        raise SystemExit("major/minor/patch/protocolVersion must fit in one byte")
    if ota != expected_ota or not 0 < ota <= 0xFFFF:
        raise SystemExit(
            f"otaVersion must be major*10000 + minor*100 + patch ({expected_ota}) "
            "and fit in the Goodix 16-bit image field"
        )

    header = f"""// Generated by tools/version/sync-version.py from version.json.
#ifndef INKTAG_VERSION_H
#define INKTAG_VERSION_H

#define INKTAG_VERSION_MAJOR {major}u
#define INKTAG_VERSION_MINOR {minor}u
#define INKTAG_VERSION_PATCH {patch}u
#define INKTAG_VERSION_STRING \"{version}\"
#define INKTAG_PROTOCOL_VERSION 0x{protocol:02x}u
#define INKTAG_OTA_VERSION {ota}u
#define INKTAG_VERSION_GATT_BYTES \\
    {{INKTAG_PROTOCOL_VERSION, INKTAG_VERSION_MAJOR, INKTAG_VERSION_MINOR, INKTAG_VERSION_PATCH}}

#endif
"""
    write_if_changed(repo / "firmware/common/epd/inktag_version.h", header)
    gui_header = f'''// Generated by tools/version/sync-version.py from version.json.
#ifndef INKTAG_GUI_VERSION_H
#define INKTAG_GUI_VERSION_H
#define INKTAG_GUI_FIRMWARE_LABEL "v{version}"
#endif
'''
    write_if_changed(repo / "firmware/common/gui/inktag_gui_version.h", gui_header)
    recovery_header = f'''// Generated by tools/version/sync-version.py from version.json.
#ifndef INKTAG_RECOVERY_VERSION_H
#define INKTAG_RECOVERY_VERSION_H
#define INKTAG_RECOVERY_VERSION_MAJOR {recovery_major}u
#define INKTAG_RECOVERY_VERSION_MINOR {recovery_minor}u
#define INKTAG_RECOVERY_VERSION_PATCH {recovery_patch}u
#define INKTAG_RECOVERY_VERSION_STRING "{recovery_version}"
/* Major is the native compatibility epoch; minor/patch identify software. */
#define INKTAG_RECOVERY_EPOCH INKTAG_RECOVERY_VERSION_MAJOR
#define INKTAG_RECOVERY_INFO_BYTES \\
    {{'I','K','R','V',INKTAG_RECOVERY_VERSION_MAJOR,INKTAG_RECOVERY_VERSION_MINOR,INKTAG_RECOVERY_VERSION_PATCH,INKTAG_RECOVERY_EPOCH}}
#endif
'''
    write_if_changed(repo / "firmware/common/ota/inktag_recovery_version.h", recovery_header)


if __name__ == "__main__":
    main()
