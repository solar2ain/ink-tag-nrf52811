#!/usr/bin/env python3
"""Keep SDK request input immutable; acknowledge durable object boundaries."""
import argparse
import hashlib
from pathlib import Path

EXPECTED_SHA256 = '862f32ca53e3921a41458732346214f2a534c7a4f43204875805205c02a17d7e'
OLD = '''        /* Provide response to transport */
        p_req->callback.response(&res, p_req->p_context);

        if (NRF_DFU_SAVE_PROGRESS_IN_FLASH)
        {
            /* Allowing skipping settings backup to save time and flash wear. */
            ret = nrf_dfu_settings_write_and_backup(NULL);
            UNUSED_RETURN_VALUE(ret);
        }'''
NEW = '''        if (NRF_DFU_SAVE_PROGRESS_IN_FLASH)
        {
            uint32_t const offset = s_dfu_settings.progress.firmware_image_offset;
            uint32_t const crc = s_dfu_settings.progress.firmware_image_crc;
            ret = nrf_dfu_settings_write_and_backup(NULL);
            /* The next object must not race checkpoint writes. Wait with
             * SoftDevice IRQs enabled, then verify the persisted boundary. */
            while (nrf_fstorage_is_busy(NULL)) (void)sd_app_evt_wait();
            nrf_dfu_settings_reinit();
            if (ret != NRF_SUCCESS ||
                s_dfu_settings.progress.firmware_image_offset != offset ||
                s_dfu_settings.progress.firmware_image_crc != crc)
            {
                res.result = NRF_DFU_RES_CODE_OPERATION_FAILED;
            }
        }
        p_req->callback.response(&res, p_req->p_context);'''

WRITE_FAILURE = '''        p_req->callback.write((void*)p_req->write.p_data);
        return;
    }

    /* Update the CRC of the firmware image. */'''
WRITE_REJECTION = '''        p_res->result = ret == NRF_ERROR_NO_MEM ?
            NRF_DFU_RES_CODE_INSUFFICIENT_RESOURCES : NRF_DFU_RES_CODE_OPERATION_FAILED;
        p_req->callback.write((void*)p_req->write.p_data);
        return;
    }

    /* Update the CRC of the firmware image. */'''


def reject_failed_writes(source):
    # Do not leave the dispatcher's default SUCCESS after a rejected store.
    # Preserve the SDK buffer release and its unchanged offset/CRC boundary.
    if source.count(WRITE_FAILURE) != 1:
        raise ValueError('Expected exactly one failed data-write release')
    return source.replace(WRITE_FAILURE, WRITE_REJECTION, 1)


def materialize(path):
    payload = path.read_bytes()
    if hashlib.sha256(payload).hexdigest() != EXPECTED_SHA256:
        raise ValueError('DFU request source differs from locked nRF5 SDK 17.1.0')
    source = payload.decode('utf-8').replace('\r\n', '\n')
    if source.count(OLD) != 1:
        raise ValueError('Expected exactly one partial-object acknowledgement')
    return ('/* Generated by tools/sdk/materialize-nordic-dfu-request.py. */\n' +
        reject_failed_writes(source).replace('#include <stdint.h>', '#include "nrf_soc.h"\n#include <stdint.h>', 1).replace(OLD, NEW))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check-only', action='store_true')
    args = parser.parse_args()
    rendered = materialize(args.source)
    if not args.check_only:
        if args.output is None:
            parser.error('--output is required')
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(rendered, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
