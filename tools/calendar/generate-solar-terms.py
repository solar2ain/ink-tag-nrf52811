#!/usr/bin/env python3
"""Reproduce InkTag's UTC+08 solar-term resource from a pinned JPL kernel.

Ordinary firmware builds consume the checked-in resource and need no astronomy
packages or network. Regeneration requires requirements.txt and an explicitly
supplied, unmodified DE440s kernel; this program never downloads inputs.
"""
import argparse
import csv
import datetime
import hashlib
import importlib.metadata
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
KERNEL_SHA256 = 'c1c7feeab882263fc493a9d5a5b2ddd71b54826cdf65d8d17a76126b260a49f2'
KERNEL_URL = 'https://naif.jpl.nasa.gov/pub/naif/generic_kernels/spk/planets/de440s.bsp'
PACKAGES = {'skyfield': '1.53', 'numpy': '2.2.6', 'jplephem': '2.23', 'sgp4': '2.24'}
BASE_DAYS = (6, 20, 4, 19, 6, 21, 5, 20, 6, 21, 6, 21,
             7, 23, 8, 23, 8, 23, 8, 24, 8, 22, 7, 22)
START_YEAR, END_YEAR = 2000, 2050


def encode(records):
    """Encode civil dates in the established 3-byte/year resource ABI."""
    expected = [(year, term) for year in range(START_YEAR, END_YEAR + 1)
                for term in range(24)]
    if [(r['year'], r['term']) for r in records] != expected:
        raise ValueError('Need exactly 24 ordered terms per year, 2000..2050')
    image = bytearray(160)
    for row in records:
        year, term, day = row['year'], row['term'], row['day']
        if row['month'] != term // 2 + 1:
            raise ValueError('Term falls outside its encoded month')
        direction = 1 if year < 2044 and term in (1, 11, 18, 21) else -1
        bit = (day - BASE_DAYS[term]) * direction
        if bit not in (0, 1):
            raise ValueError('Date does not fit the existing resource ABI')
        image[(year - START_YEAR) * 3 + term // 8] |= bit << (7 - term % 8)
    return bytes(image)


def calculate(kernel):
    if hashlib.sha256(kernel.read_bytes()).hexdigest() != KERNEL_SHA256:
        raise ValueError('DE440s kernel hash mismatch')
    for name, version in PACKAGES.items():
        if importlib.metadata.version(name) != version:
            raise ValueError('Install the pinned tools/calendar/requirements.txt')
    from skyfield.api import load, load_file
    from skyfield import almanac, almanac_east_asia
    ephemeris = load_file(str(kernel))
    timescale = load.timescale(builtin=True)
    try:
        times, terms = almanac.find_discrete(
            timescale.utc(START_YEAR, 1, 1), timescale.utc(END_YEAR + 1, 1, 1),
            almanac_east_asia.solar_terms(ephemeris))
        timezone = datetime.timezone(datetime.timedelta(hours=8))
        records = []
        for instant, term in zip(times, terms):
            date = instant.utc_datetime().astimezone(timezone)
            records.append(dict(year=date.year, term=(int(term) + 5) % 24,
                                month=date.month, day=date.day))
        return records
    finally:
        ephemeris.close()


def products(records):
    image = encode(records)
    resource = ('/* Generated by tools/calendar/generate-solar-terms.py.\n'
                ' * JPL DE440s / Skyfield; civil dates in UTC+08:00.\n'
                ' */\nstatic const uint8_t YearMonthBit[160] = {\n')
    for offset in range(0, len(image), 12):
        resource += '    ' + ', '.join('0x%02x' % b for b in image[offset:offset + 12]) + ',\n'
    resource += '};\n'
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=('year', 'term', 'month', 'day'),
                            lineterminator='\n')
    writer.writeheader()
    writer.writerows(records)
    data = {
        'firmware/common/gui/inktag_solar_terms.inc': resource.encode(),
        'tools/calendar/solar-terms-2000-2050.csv': stream.getvalue().encode(),
    }
    provenance = {
        'schemaVersion': 1,
        'method': 'Apparent geocentric solar ecliptic longitude at 15-degree crossings',
        'civilTimezone': 'UTC+08:00', 'firstYear': START_YEAR, 'lastYear': END_YEAR,
        'records': len(records), 'resourceBytes': len(image),
        'resourceSha256': hashlib.sha256(image).hexdigest(),
        'kernel': {'url': KERNEL_URL, 'sha256': KERNEL_SHA256},
        'packages': PACKAGES,
        'timescale': 'Skyfield 1.53 bundled leap seconds and Delta-T data; builtin=True',
        'filesSha256': {name: hashlib.sha256(value).hexdigest() for name, value in data.items()},
    }
    data['tools/calendar/solar-terms-source.json'] = (
        json.dumps(provenance, indent=2) + '\n').encode()
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--kernel', type=Path, required=True)
    parser.add_argument('--write', action='store_true',
                        help='Write generated files; default verifies checked-in bytes')
    args = parser.parse_args()
    for name, data in products(calculate(args.kernel)).items():
        path = ROOT / name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif not path.is_file() or path.read_bytes() != data:
            raise SystemExit('Generated file differs: ' + name)
    print('PASS 1224 solar terms and 160-byte resource; ' +
          ('written' if args.write else 'reproduced'))


if __name__ == '__main__':
    main()
